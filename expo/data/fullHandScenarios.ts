// Helper to get a random scenario
export function getRandomFullHandScenario(excludeIds: string[] = []): FullHandScenario | null {
  const available = FULL_HAND_SCENARIOS.filter(s => !excludeIds.includes(s.id));
  if (available.length === 0) return null;
  return available[Math.floor(Math.random() * available.length)];
}

// Helper to get scenarios by difficulty
export function getFullHandScenariosByDifficulty(
  difficulty: 'beginner' | 'intermediate' | 'advanced'
): FullHandScenario[] {
  return FULL_HAND_SCENARIOS.filter(s => s.difficulty === difficulty);
}
